const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync('lib/learning/text-session.ts', 'utf8');
const context = vm.createContext({ exports: {} });
vm.runInContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, context);
const replace = context.exports.textSession;
const q = (id, type = 'multiple_choice', audioUrl = null) => ({ id, type, audioUrl });
const original = { level: 'A1', questions: [q('done'), q('audio1', 'listening'), q('text'), q('audio2', 'listening'), q('end')] };
const bank = [original, { level: 'A2', questions: [q('wrong-level')] }, { level: 'A1', questions: [q('prior'), q('new1'), q('new2'), q('audio3', 'listening'), q('has-audio', 'fill_blank', '/audio.wav')] }];
const result = replace(original, bank, 1, ['done', 'prior']);
assert.equal(result.length, 5);
assert.deepEqual(Array.from(result, x => x.id), ['done', 'new1', 'text', 'new2', 'end']);
assert.equal(new Set(result.map(x => x.id)).size, 5);
assert.equal(original.questions[1].id, 'audio1');
assert.equal(result[0], original.questions[0]);
assert.equal(replace(original, [original], 1, ['done']), null);
const preserved = replace(original, bank, 2, ['audio2']);
assert.equal(preserved[1].id, 'audio1');
assert.equal(preserved[3].id, 'audio2');
const duplicateBank = [original, { level: 'A1', questions: [q('new1'), q('new1'), q('new2')] }];
assert.equal(new Set(replace(original, duplicateBank, 1, []).map(x => x.id)).size, 5);
console.log('Text-session replacement checks passed.');
