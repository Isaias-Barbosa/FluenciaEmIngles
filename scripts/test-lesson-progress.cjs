const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const source = fs.readFileSync('app/learn/components/lesson-progress.tsx', 'utf8');
const context = vm.createContext({ exports: {}, require });
vm.runInContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2020 } }).outputText, context);
const questions = Array.from({ length: 5 }, (_, i) => ({ id: `q${i}` }));
const render = (completedIds, soundsEnabled = true) => renderToStaticMarkup(React.createElement(context.exports.LessonProgress, { questions, questionIndex: 1, status: { completedIds, soundsEnabled, onToggleSounds() {} } }));
let html = render([]);
assert.match(html, /0 acertos/);
assert.match(html, /aria-valuenow="0"/);
assert.match(html, /aria-current="step" aria-label="Questão 2: atual"/);
html = render(['q0', 'q0', 'outside-this-lesson']);
assert.match(html, /1 acerto</);
assert.match(html, /aria-valuenow="1"/);
assert.match(html, /width:20%/);
assert.match(html, /Questão 1: acertada/);
assert.equal((html.match(/<li /g) || []).length, 5);
html = render(questions.map(q => q.id), false);
assert.match(html, /5 acertos/);
assert.match(html, /Lição concluída/);
assert.match(html, /Sons desligados/);
assert.match(html, /aria-pressed="false"/);
console.log('Lesson progress: counts, duplicate IDs, saved progress, question states and mute label passed.');
