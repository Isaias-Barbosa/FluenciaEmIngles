const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const context = vm.createContext({ exports: {}, URL });
vm.runInContext(ts.transpileModule(fs.readFileSync('lib/learning/web-question.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, context);
const { parseWebQuestion, applyReplacement } = context.exports;
const source = 'https://learnenglish.britishcouncil.org/grammar/a1-a2-grammar';
const question = { level:'A1', prompt:'Complete: She ___ a teacher.', choices:['is','are','am','be'], correct_option:0, explanation:'Use is with she.', hint:'Pense na terceira pessoa.', source_url:source, source_title:'British Council' };
const response = (q = question, searches = true) => ({ status:'completed', output:[...(searches ? [{ type:'web_search_call', status:'completed', action:{ sources:[{url:source}] } }] : []), {type:'message', content:[{type:'output_text',text:JSON.stringify(q)}]}] });
assert.equal(parseWebQuestion(response(),'A1').correct_option,0);
assert.throws(() => parseWebQuestion(response(question,false),'A1'), /não foi executada/);
assert.throws(() => parseWebQuestion(response({...question,level:'C2'}),'A1'), /validar/);
assert.throws(() => parseWebQuestion(response({...question,source_url:'https://learnenglish.britishcouncil.org/not-in-search'}),'A1'), /validar/);
assert.throws(() => parseWebQuestion(response({...question,source_url:'https://learnenglish.britishcouncil.org.evil.test/'}),'A1'), /validar/);
assert.throws(() => parseWebQuestion(response({...question,choices:['is','Is','am','be']}),'A1'), /validar/);
assert.throws(() => parseWebQuestion(response({...question,correct_option:4}),'A1'), /validar/);
assert.throws(() => parseWebQuestion({...response(),status:'incomplete'},'A1'), /não foi concluída/);
const original = {id:'original-audio',type:'listening',prompt:'Listen',options:[],audioUrl:'/audio.wav',hint:'Old hint',passage:'Old passage'};
const saved = {question_id:original.id, prompt:question.prompt, choices:question.choices, source_url:source, source_title:question.source_title};
const replacement = applyReplacement(original,saved);
assert.equal(replacement.id,original.id);
assert.equal(replacement.audioUrl,null);
assert.equal(replacement.hint,null);
assert.equal(replacement.type,'multiple_choice');
assert.equal(original.type,'listening');
assert.throws(() => applyReplacement(original,{...saved,question_id:'another-question'}),/inválida/);
const group = [{...original,id:'q1'},{...original,id:'q2'},original,{...original,id:'q4'},{...original,id:'q5'}];
const reloaded = group.map(q => q.id === saved.question_id ? applyReplacement(q,saved) : q);
assert.deepEqual(reloaded.map(q=>q.id),group.map(q=>q.id));
assert.equal(reloaded.length,5);
const completedIds = new Set(['q1','q2',replacement.id,'q4','q5',replacement.id]);
assert.equal(reloaded.filter(q=>completedIds.has(q.id)).length,5);
console.log('Web question validation and same-slot/reload/progress regression checks passed.');
